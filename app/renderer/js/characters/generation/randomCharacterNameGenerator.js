const NAME_STYLES = Object.freeze([
  'japanese-full', 'japanese-full', 'japanese-full', 'japanese-given',
  'western-full', 'western-full', 'western-given',
  'fantasy-full', 'fantasy-full', 'fantasy-given',
  'nickname', 'nickname',
]);

function pick(values, rng) {
  return values[Math.floor(rng() * values.length)];
}

export function generateRandomCharacterName(rng = Math.random) {
  if (typeof rng !== 'function') throw new TypeError('乱数生成器が不正です。');
  const style = pick(NAME_STYLES, rng);
  if (style === 'japanese-full') return `${pick(JAPANESE_SURNAMES, rng)} ${pick(JAPANESE_GIVEN_NAMES, rng)}`;
  if (style === 'japanese-given') return pick(JAPANESE_GIVEN_NAMES, rng);
  if (style === 'western-full') return `${pick(WESTERN_GIVEN_NAMES, rng)}・${pick(WESTERN_SURNAMES, rng)}`;
  if (style === 'western-given') return pick(WESTERN_GIVEN_NAMES, rng);
  if (style === 'fantasy-full') return `${pick(FANTASY_GIVEN_NAMES, rng)}・${pick(FANTASY_FAMILY_NAMES, rng)}`;
  if (style === 'fantasy-given') return pick(FANTASY_GIVEN_NAMES, rng);
  return `${pick(NICKNAME_BASES, rng)}ちゃん`;
}
